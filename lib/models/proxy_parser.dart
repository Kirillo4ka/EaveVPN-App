import 'dart:convert';

String safeUriDecode(String input) {
  try {
    return Uri.decodeComponent(input);
  } catch (_) {
    try {
      return Uri.decodeQueryComponent(input);
    } catch (_) {
      return input;
    }
  }
}

Map<String, String> safeSplitQuery(String query) {
  final result = <String, String>{};
  if (query.isEmpty) return result;
  for (final part in query.split('&')) {
    if (part.isEmpty) continue;
    final idx = part.indexOf('=');
    if (idx != -1) {
      final key = safeUriDecode(part.substring(0, idx));
      final val = safeUriDecode(part.substring(idx + 1));
      result[key] = val;
    } else {
      result[safeUriDecode(part)] = '';
    }
  }
  return result;
}

String convertProxyUrisToMihomoYaml(List<String> uris) {
  final proxies = <String>[];
  final names = <String>[];
  final seenNames = <String, int>{};

  int proxyIndex = 1;
  for (int i = 0; i < uris.length; i++) {
    final raw = uris[i].trim();
    if (raw.isEmpty || raw.startsWith('#')) continue;
    var defaultName = 'Proxy $proxyIndex';
    final yaml = _parseProxyUri(raw, defaultName);
    if (yaml.isNotEmpty) {
      var name = _extractName(yaml);
      if (name.isEmpty) name = defaultName;
      if (seenNames.containsKey(name)) {
        seenNames[name] = seenNames[name]! + 1;
        final uniqueName = '$name (${seenNames[name]})';
        final adjustedYaml = yaml.replaceFirst('name: "$name"', 'name: "$uniqueName"');
        proxies.add(adjustedYaml);
        names.add(uniqueName);
      } else {
        seenNames[name] = 1;
        proxies.add(yaml);
        names.add(name);
      }
      proxyIndex++;
    }
  }
  if (proxies.isEmpty) return '';

  final buf = StringBuffer();
  buf.writeln('# Generated by FlClash-Mod Smart Importer');
  buf.writeln('mixed-port: 7890');
  buf.writeln('allow-lan: false');
  buf.writeln('mode: rule');
  buf.writeln('log-level: info');
  buf.writeln('unified-delay: true');
  buf.writeln('tcp-concurrent: true');
  buf.writeln('');
  buf.writeln('dns:');
  buf.writeln('  enable: true');
  buf.writeln('  ipv6: false');
  buf.writeln('  enhanced-mode: fake-ip');
  buf.writeln('  fake-ip-range: 198.18.0.1/16');
  buf.writeln('  nameserver:');
  buf.writeln('    - 77.88.8.8');
  buf.writeln('    - 77.88.8.1');
  buf.writeln('    - 8.8.8.8');
  buf.writeln('    - https://dns.yandex.ru/dns-query');
  buf.writeln('    - https://cloudflare-dns.com/dns-query');
  buf.writeln('');
  buf.writeln('proxies:');
  for (final p in proxies) {
    buf.writeln(p);
  }
  buf.writeln('');
  buf.writeln('proxy-groups:');
  buf.writeln('  - name: PROXY');
  buf.writeln('    type: select');
  buf.writeln('    proxies:');
