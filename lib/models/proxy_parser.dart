  }
  buf.writeln('      - DIRECT');
  buf.writeln('');
  buf.writeln('rules:');
  buf.writeln('  - MATCH,PROXY');
  return buf.toString();
}

String _extractName(String proxyYaml) {
  for (final line in proxyYaml.split('\n')) {
    var t = line.trim();
    if (t.startsWith('-')) {
      t = t.substring(1).trim();
    }
    if (t.startsWith('name:')) {
      var n = t.substring(5).trim();
      if (n.startsWith('"') && n.endsWith('"') && n.length >= 2) {
        n = n.substring(1, n.length - 1);
      }
      return n;
    }
  }
  return '';
}

String _normalizeFp(String rawFp) {
  final lower = rawFp.trim().toLowerCase();
  if (['chrome', 'firefox', 'safari', 'ios', 'android', 'edge', '360', 'random', 'randomized'].contains(lower)) {
    return lower;
  }
  return 'chrome';
}

String _parseProxyUri(String uri, String defaultName) {
  final lower = uri.toLowerCase();
  try {
    if (lower.startsWith('vmess://')) return _parseVmess(uri, defaultName);
    if (lower.startsWith('vless://')) return _parseVless(uri, defaultName);
    if (lower.startsWith('trojan://')) return _parseTrojan(uri, defaultName);
    if (lower.startsWith('ss://')) return _parseSS(uri, defaultName);
    if (lower.startsWith('hysteria2://') || lower.startsWith('hy2://')) {
      return _parseHysteria2(uri, defaultName);
    }
    if (lower.startsWith('hysteria://')) return _parseHysteria(uri, defaultName);
    if (lower.startsWith('tuic://')) return _parseTuic(uri, defaultName);
  } catch (e) {
    print('Error parsing $uri: $e');
  }
  return '';
}

String _parseVless(String uri, String defaultName) {
  try {
    var raw = uri.substring('vless://'.length);
    String name = defaultName;
    if (raw.contains('#')) {
      final idx = raw.lastIndexOf('#');
      name = _esc(safeUriDecode(raw.substring(idx + 1)).trim());
      raw = raw.substring(0, idx);
    }
    String query = '';
    if (raw.contains('?')) {
      final idx = raw.indexOf('?');
      query = raw.substring(idx + 1);
      raw = raw.substring(0, idx);
    }
    final atIdx = raw.lastIndexOf('@');
    final uuid = raw.substring(0, atIdx);
    final (server, port) = _splitHostPort(raw.substring(atIdx + 1), 443);
    final p = safeSplitQuery(query);
    final type = p['type'] ?? 'tcp';
    final security = p['security'] ?? 'none';
    final flow = p['flow'] ?? '';
    final path = safeUriDecode(p['path'] ?? '/');
    final host = p['host'] ?? '';
    final sni = p['sni'] ?? '';
    final fp = _normalizeFp(p['fp'] ?? 'chrome');
    final pbk = p['pbk'] ?? '';
    final sid = p['sid'] ?? '';
    final grpcSvc = p['serviceName'] ?? '';
    final alpn = p['alpn'] ?? '';
    final insecure = p['insecure'] == '1' || p['allowInsecure'] == '1';

    final sb = StringBuffer();
    sb.writeln('  - name: "$name"');
    sb.writeln('    type: vless');
    sb.writeln('    server: $server');
    sb.writeln('    port: $port');
    sb.writeln('    uuid: $uuid');
    sb.writeln('    udp: true');

    if (type == 'ws') {
      sb.writeln('    network: ws');
      sb.writeln('    ws-opts:');
      sb.writeln('      path: "${_esc(path)}"');
      if (host.isNotEmpty) {
        sb.writeln('      headers:');
        sb.writeln('        Host: $host');
      }
    } else if (type == 'grpc') {
      sb.writeln('    network: grpc');
      sb.writeln('    grpc-opts:');
      sb.writeln('      grpc-service-name: "${_esc(grpcSvc)}"');
    } else if (type == 'h2' || type == 'http') {
      sb.writeln('    network: h2');
      sb.writeln('    h2-opts:');
      sb.writeln('      path: "${_esc(path)}"');
      if (host.isNotEmpty) sb.writeln('      host: [$host]');
    } else {
      sb.writeln('    network: tcp');
      if (flow.isNotEmpty) sb.writeln('    flow: $flow');
    }

    if (security == 'tls') {
      sb.writeln('    tls: true');
      if (sni.isNotEmpty) sb.writeln('    servername: $sni');
      sb.writeln('    client-fingerprint: $fp');
      if (alpn.isNotEmpty) {
        sb.writeln('    alpn:');
        for (final a in alpn.split(',')) {
          if (a.trim().isNotEmpty) sb.writeln('      - ${a.trim()}');
        }
      }
      if (insecure) sb.writeln('    skip-cert-verify: true');
    } else if (security == 'reality') {
      sb.writeln('    tls: true');
      if (sni.isNotEmpty) sb.writeln('    servername: $sni');
      sb.writeln('    client-fingerprint: $fp');
      if (alpn.isNotEmpty) {
        sb.writeln('    alpn:');
        for (final a in alpn.split(',')) {
          if (a.trim().isNotEmpty) sb.writeln('      - ${a.trim()}');
        }
      }
      sb.writeln('    reality-opts:');
      sb.writeln('      public-key: "$pbk"');
      if (sid.isNotEmpty) sb.writeln('      short-id: "$sid"');
    }

    return sb.toString().trimRight();
  } catch (e) {
    print('Vless error: $e');
    return '';
  }
}

