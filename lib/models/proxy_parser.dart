String _parseSS(String uri, String defaultName) {
  try {
    var raw = uri.substring('ss://'.length);
    String name = defaultName;
    if (raw.contains('#')) {
      final idx = raw.lastIndexOf('#');
      name = _esc(safeUriDecode(raw.substring(idx + 1)).trim());
      raw = raw.substring(0, idx);
    }
    if (raw.contains('?')) raw = raw.substring(0, raw.indexOf('?'));
    String method, password, server;
    int port;
    if (raw.contains('@')) {
      final atIdx = raw.lastIndexOf('@');
      final userInfo = raw.substring(0, atIdx);
      final hostPort = raw.substring(atIdx + 1);
      String decoded;
      try {
        decoded = utf8.decode(base64.decode(_padBase64(userInfo)));
      } catch (_) {
        decoded = userInfo;
      }
      final ci = decoded.indexOf(':');
      method = decoded.substring(0, ci);
      password = decoded.substring(ci + 1);
      final hp = _splitHostPort(hostPort, 8388);
      server = hp.$1;
      port = hp.$2;
    } else {
      final decoded = utf8.decode(base64.decode(_padBase64(raw)));
      final ci = decoded.indexOf(':');
      method = decoded.substring(0, ci);
      final rest = decoded.substring(ci + 1);
      final atIdx = rest.lastIndexOf('@');
      password = rest.substring(0, atIdx);
      final hp = _splitHostPort(rest.substring(atIdx + 1), 8388);
      server = hp.$1;
      port = hp.$2;
    }
    final sb = StringBuffer();
    sb.writeln('  - name: "$name"');
    sb.writeln('    type: ss');
    sb.writeln('    server: $server');
    sb.writeln('    port: $port');
    sb.writeln('    cipher: $method');
    sb.writeln('    password: "${_esc(password)}"');
    sb.writeln('    udp: true');
    return sb.toString().trimRight();
  } catch (_) {
    return '';
  }
}

